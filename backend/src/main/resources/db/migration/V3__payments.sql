CREATE SEQUENCE receipt_number_seq;

CREATE TABLE payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id     BIGINT        NOT NULL REFERENCES flat (id),
    amount      NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    method      VARCHAR(16)   NOT NULL CHECK (method IN ('ONLINE_TEST', 'UPI', 'BANK_TRANSFER', 'CHEQUE')),
    source      VARCHAR(16)   NOT NULL CHECK (source IN ('GATEWAY', 'BANK_STATEMENT', 'MANUAL')),
    gateway_ref VARCHAR(40),
    utr         VARCHAR(40),
    paid_on     DATE          NOT NULL,
    receipt_no  VARCHAR(20)   NOT NULL UNIQUE,
    posted_by   BIGINT        REFERENCES app_user (id),
    created_at  TIMESTAMPTZ   NOT NULL
);

CREATE UNIQUE INDEX payment_gateway_ref_posted_once ON payment (gateway_ref) WHERE gateway_ref IS NOT NULL;
CREATE UNIQUE INDEX payment_utr_posted_once ON payment (utr) WHERE utr IS NOT NULL;
CREATE INDEX idx_payment_flat ON payment (flat_id, paid_on);

CREATE TABLE payment_allocation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id         BIGINT        NOT NULL REFERENCES payment (id),
    bill_id            BIGINT        REFERENCES bill (id),
    late_fee_charge_id BIGINT        REFERENCES late_fee_charge (id),
    amount             NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    allocated_on       DATE          NOT NULL,
    CONSTRAINT allocation_targets_exactly_one_item CHECK ((bill_id IS NULL) <> (late_fee_charge_id IS NULL))
);

CREATE INDEX idx_payment_allocation_payment ON payment_allocation (payment_id);
CREATE INDEX idx_payment_allocation_bill ON payment_allocation (bill_id) WHERE bill_id IS NOT NULL;
CREATE INDEX idx_payment_allocation_charge ON payment_allocation (late_fee_charge_id) WHERE late_fee_charge_id IS NOT NULL;

CREATE TABLE payment_intent (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id         BIGINT        NOT NULL REFERENCES flat (id),
    amount          NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    idempotency_key VARCHAR(64)   NOT NULL UNIQUE,
    status          VARCHAR(16)   NOT NULL CHECK (status IN ('CREATED', 'SUCCEEDED', 'FAILED')),
    gateway_ref     VARCHAR(40)   NOT NULL UNIQUE,
    created_by      BIGINT        NOT NULL REFERENCES app_user (id),
    created_at      TIMESTAMPTZ   NOT NULL,
    completed_at    TIMESTAMPTZ,
    CONSTRAINT payment_intent_completed_when_final CHECK ((status = 'CREATED') = (completed_at IS NULL))
);

CREATE FUNCTION reject_money_record_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed; post a reversing entry instead', TG_TABLE_NAME, TG_OP;
END;
$$;

CREATE TRIGGER payment_no_update_or_delete
    BEFORE UPDATE OR DELETE ON payment
    FOR EACH ROW EXECUTE FUNCTION reject_money_record_change();

CREATE TRIGGER payment_allocation_no_update_or_delete
    BEFORE UPDATE OR DELETE ON payment_allocation
    FOR EACH ROW EXECUTE FUNCTION reject_money_record_change();
