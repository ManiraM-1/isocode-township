CREATE TABLE bill (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id     BIGINT        NOT NULL REFERENCES flat (id),
    period      DATE          NOT NULL CHECK (EXTRACT(DAY FROM period) = 1),
    area_sqft   INT           NOT NULL CHECK (area_sqft > 0),
    rate        NUMERIC(8,2)  NOT NULL CHECK (rate > 0),
    amount      NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    due_date    DATE          NOT NULL,
    amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT bill_one_per_flat_month UNIQUE (flat_id, period),
    CONSTRAINT bill_due_in_or_after_period CHECK (due_date >= period),
    CONSTRAINT bill_paid_within_amount CHECK (amount_paid >= 0 AND amount_paid <= amount)
);

CREATE INDEX idx_bill_unpaid_due ON bill (due_date) WHERE amount_paid < amount;

CREATE TABLE late_fee_charge (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id    BIGINT        NOT NULL REFERENCES flat (id),
    bill_id    BIGINT        NOT NULL REFERENCES bill (id),
    from_date  DATE          NOT NULL,
    to_date    DATE          NOT NULL,
    amount     NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT late_fee_charge_dates CHECK (to_date >= from_date),
    CONSTRAINT late_fee_charge_once_per_period UNIQUE (bill_id, to_date)
);

CREATE INDEX idx_late_fee_charge_flat ON late_fee_charge (flat_id);

CREATE TABLE ledger_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id     BIGINT        NOT NULL REFERENCES flat (id),
    entry_date  DATE          NOT NULL,
    type        VARCHAR(16)   NOT NULL CHECK (type IN ('BILL', 'LATE_FEE', 'PAYMENT', 'REVERSAL')),
    debit       NUMERIC(12,2) NOT NULL DEFAULT 0,
    credit      NUMERIC(12,2) NOT NULL DEFAULT 0,
    ref_type    VARCHAR(32)   NOT NULL,
    ref_id      BIGINT        NOT NULL,
    description VARCHAR(200)  NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    created_by  BIGINT        REFERENCES app_user (id),
    CONSTRAINT ledger_amounts_not_negative CHECK (debit >= 0 AND credit >= 0),
    CONSTRAINT ledger_exactly_one_side CHECK ((debit > 0) <> (credit > 0)),
    CONSTRAINT ledger_one_entry_per_source UNIQUE (type, ref_type, ref_id)
);

CREATE INDEX idx_ledger_entry_flat_date ON ledger_entry (flat_id, entry_date, id);

CREATE FUNCTION reject_ledger_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'ledger_entry is append-only: % is not allowed; post a reversing entry instead', TG_OP;
END;
$$;

CREATE TRIGGER ledger_entry_no_update_or_delete
    BEFORE UPDATE OR DELETE ON ledger_entry
    FOR EACH ROW EXECUTE FUNCTION reject_ledger_change();

CREATE TRIGGER ledger_entry_no_truncate
    BEFORE TRUNCATE ON ledger_entry
    FOR EACH STATEMENT EXECUTE FUNCTION reject_ledger_change();
