CREATE TABLE bank_import (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name           VARCHAR(200) NOT NULL,
    file_sha256         VARCHAR(64)  NOT NULL,
    uploaded_by         BIGINT       NOT NULL REFERENCES app_user (id),
    uploaded_at         TIMESTAMPTZ  NOT NULL,
    total_rows          INT          NOT NULL,
    auto_posted         INT          NOT NULL,
    reconciled          INT          NOT NULL,
    suggested           INT          NOT NULL,
    conflicts           INT          NOT NULL,
    unmatched           INT          NOT NULL,
    duplicates          INT          NOT NULL,
    possible_duplicates INT          NOT NULL,
    non_credit          INT          NOT NULL,
    errors              INT          NOT NULL
);

CREATE INDEX idx_bank_import_sha ON bank_import (file_sha256);

CREATE TABLE bank_row (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id           BIGINT        NOT NULL REFERENCES bank_import (id),
    row_no              INT           NOT NULL,
    txn_date            DATE,
    description         VARCHAR(500),
    reference           VARCHAR(100),
    utr                 VARCHAR(40),
    vpa                 VARCHAR(100),
    gateway_ref         VARCHAR(40),
    amount              NUMERIC(12,2),
    debit               NUMERIC(12,2),
    row_hash            VARCHAR(64),
    duplicate_of_row_id BIGINT        REFERENCES bank_row (id),
    decision            VARCHAR(24)   NOT NULL CHECK (decision IN ('DUPLICATE', 'NON_CREDIT', 'POSSIBLE_DUPLICATE',
                            'RECONCILED_GATEWAY', 'CONFLICT', 'AUTO_POSTED', 'SUGGESTED', 'UNMATCHED', 'PARSE_ERROR')),
    suggested_flat_id   BIGINT        REFERENCES flat (id),
    candidates          JSONB         NOT NULL DEFAULT '[]'::jsonb,
    confidence          VARCHAR(8)    CHECK (confidence IN ('HIGH', 'MEDIUM', 'LOW')),
    reasons             JSONB         NOT NULL DEFAULT '[]'::jsonb,
    payment_id          BIGINT        REFERENCES payment (id),
    resolution          VARCHAR(16)   CHECK (resolution IN ('CONFIRMED', 'ASSIGNED', 'IGNORED')),
    resolved_by         BIGINT        REFERENCES app_user (id),
    resolved_at         TIMESTAMPTZ,
    resolution_note     VARCHAR(500),
    parse_error         VARCHAR(300),
    CONSTRAINT bank_row_unique_in_import UNIQUE (import_id, row_no),
    CONSTRAINT bank_row_resolution_complete CHECK ((resolution IS NULL) = (resolved_at IS NULL))
);

CREATE INDEX idx_bank_row_hash ON bank_row (row_hash);
CREATE INDEX idx_bank_row_utr ON bank_row (utr) WHERE utr IS NOT NULL;
CREATE INDEX idx_bank_row_queue ON bank_row (txn_date, id)
    WHERE resolution IS NULL AND decision IN ('SUGGESTED', 'CONFLICT', 'UNMATCHED', 'POSSIBLE_DUPLICATE');

CREATE TABLE known_vpa (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vpa                 VARCHAR(100) NOT NULL UNIQUE CHECK (vpa = lower(vpa)),
    flat_id             BIGINT       NOT NULL REFERENCES flat (id),
    learned_from_row_id BIGINT       REFERENCES bank_row (id),
    created_at          TIMESTAMPTZ  NOT NULL
);

CREATE TABLE late_fee_adjustment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    late_fee_charge_id BIGINT        NOT NULL REFERENCES late_fee_charge (id),
    payment_id         BIGINT        NOT NULL REFERENCES payment (id),
    amount             NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    created_at         TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_late_fee_adjustment_charge ON late_fee_adjustment (late_fee_charge_id);

CREATE TRIGGER late_fee_adjustment_no_update_or_delete
    BEFORE UPDATE OR DELETE ON late_fee_adjustment
    FOR EACH ROW EXECUTE FUNCTION reject_money_record_change();
