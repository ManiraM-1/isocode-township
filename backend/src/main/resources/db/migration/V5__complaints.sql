CREATE SEQUENCE complaint_ref_seq;

CREATE TABLE complaint (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_no                VARCHAR(20)   NOT NULL UNIQUE,
    flat_id               BIGINT        NOT NULL REFERENCES flat (id),
    raised_by             BIGINT        NOT NULL REFERENCES app_user (id),
    description           VARCHAR(1000) NOT NULL CHECK (char_length(description) BETWEEN 10 AND 1000),
    photo                 BYTEA,
    photo_content_type    VARCHAR(20)   CHECK (photo_content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    category              VARCHAR(16)   NOT NULL CHECK (category IN ('PLUMBING', 'ELECTRICAL', 'LIFT', 'SECURITY',
                              'HOUSEKEEPING', 'CIVIL', 'PEST_CONTROL', 'PARKING', 'NOISE', 'OTHER')),
    urgency               VARCHAR(8)    NOT NULL CHECK (urgency IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    ai_category           VARCHAR(16),
    ai_urgency            VARCHAR(8),
    ai_confidence         NUMERIC(3,2)  CHECK (ai_confidence BETWEEN 0 AND 1),
    ai_summary            VARCHAR(200),
    classified_by         VARCHAR(16)   NOT NULL CHECK (classified_by IN ('AI', 'RULES_FALLBACK')),
    needs_review          BOOLEAN       NOT NULL DEFAULT FALSE,
    safety_escalated      BOOLEAN       NOT NULL DEFAULT FALSE,
    safety_terms          TEXT[]        NOT NULL DEFAULT '{}',
    status                VARCHAR(12)   NOT NULL CHECK (status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    assignee_id           BIGINT        REFERENCES app_user (id),
    parent_id             BIGINT        REFERENCES complaint (id),
    created_at            TIMESTAMPTZ   NOT NULL,
    first_response_at     TIMESTAMPTZ,
    first_response_due_at TIMESTAMPTZ   NOT NULL,
    resolve_due_at        TIMESTAMPTZ   NOT NULL,
    resolved_at           TIMESTAMPTZ,
    closed_at             TIMESTAMPTZ,
    reopen_count          INT           NOT NULL DEFAULT 0 CHECK (reopen_count >= 0),
    rating                SMALLINT      CHECK (rating BETWEEN 1 AND 5),
    rating_comment        VARCHAR(500),
    CONSTRAINT complaint_photo_has_type CHECK ((photo IS NULL) = (photo_content_type IS NULL)),
    CONSTRAINT complaint_rated_only_when_closed CHECK ((status = 'CLOSED') = (rating IS NOT NULL)),
    CONSTRAINT complaint_assigned_has_assignee CHECK (status = 'OPEN' OR assignee_id IS NOT NULL),
    CONSTRAINT complaint_not_its_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX idx_complaint_flat ON complaint (flat_id, created_at DESC);
CREATE INDEX idx_complaint_status ON complaint (status);
CREATE INDEX idx_complaint_assignee_active ON complaint (assignee_id)
    WHERE status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS');

CREATE TABLE complaint_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  BIGINT       NOT NULL REFERENCES complaint (id),
    type          VARCHAR(24)  NOT NULL CHECK (type IN ('CREATED', 'AUTO_ASSIGNED', 'STATUS_CHANGED', 'ASSIGNEE_CHANGED',
                      'COMMENTED', 'CLOSED', 'REOPENED', 'CATEGORY_CHANGED', 'ESCALATED', 'ESCALATION_ACKNOWLEDGED',
                      'LINKED', 'UNLINKED')),
    actor_user_id BIGINT       REFERENCES app_user (id),
    from_value    VARCHAR(40),
    to_value      VARCHAR(40),
    note          VARCHAR(1000),
    created_at    TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_complaint_event_complaint ON complaint_event (complaint_id, created_at, id);

CREATE TABLE escalation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id     BIGINT       NOT NULL REFERENCES complaint (id),
    duty_manager_id  BIGINT       NOT NULL REFERENCES app_user (id),
    reason           VARCHAR(300) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    acknowledged_by  BIGINT       REFERENCES app_user (id),
    acknowledged_at  TIMESTAMPTZ,
    CONSTRAINT escalation_acknowledged_together CHECK ((acknowledged_by IS NULL) = (acknowledged_at IS NULL))
);

CREATE INDEX idx_escalation_open ON escalation (created_at) WHERE acknowledged_at IS NULL;
