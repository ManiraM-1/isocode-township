CREATE TABLE tower (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8)  NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL
);

CREATE TABLE flat (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(16) NOT NULL UNIQUE CHECK (code ~ '^T[0-9]{2}-[0-9]{4}$'),
    tower_id  BIGINT      NOT NULL REFERENCES tower (id),
    area_sqft INT         NOT NULL CHECK (area_sqft > 0)
);

CREATE INDEX idx_flat_tower ON flat (tower_id);

CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone           VARCHAR(16)  UNIQUE CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),
    full_name       VARCHAR(120) NOT NULL,
    role            VARCHAR(16)  NOT NULL CHECK (role IN ('RESIDENT', 'HELPDESK')),
    is_duty_manager BOOLEAN      NOT NULL DEFAULT FALSE,
    skills          TEXT[]       NOT NULL DEFAULT '{}',
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT duty_manager_is_staff CHECK (NOT is_duty_manager OR role = 'HELPDESK'),
    CONSTRAINT skills_only_for_staff CHECK (role = 'HELPDESK' OR cardinality(skills) = 0)
);

CREATE TABLE flat_member (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id  BIGINT      NOT NULL REFERENCES flat (id),
    user_id  BIGINT      NOT NULL REFERENCES app_user (id),
    relation VARCHAR(16) NOT NULL CHECK (relation IN ('OWNER', 'TENANT', 'FAMILY')),
    active   BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT flat_member_unique UNIQUE (flat_id, user_id)
);

CREATE INDEX idx_flat_member_user ON flat_member (user_id);

CREATE TABLE society_settings (
    id                               SMALLINT     PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    rate_per_sqft                    NUMERIC(8,2) NOT NULL DEFAULT 6.50  CHECK (rate_per_sqft > 0),
    due_day                          INT          NOT NULL DEFAULT 10    CHECK (due_day BETWEEN 1 AND 28),
    late_interest_pct_pa             NUMERIC(5,2) NOT NULL DEFAULT 21.00 CHECK (late_interest_pct_pa >= 0),
    first_response_minutes_critical  INT          NOT NULL DEFAULT 15    CHECK (first_response_minutes_critical > 0),
    resolve_minutes_critical         INT          NOT NULL DEFAULT 240   CHECK (resolve_minutes_critical > 0),
    first_response_minutes_high      INT          NOT NULL DEFAULT 120   CHECK (first_response_minutes_high > 0),
    resolve_minutes_high             INT          NOT NULL DEFAULT 1440  CHECK (resolve_minutes_high > 0),
    first_response_minutes_medium    INT          NOT NULL DEFAULT 480   CHECK (first_response_minutes_medium > 0),
    resolve_minutes_medium           INT          NOT NULL DEFAULT 4320  CHECK (resolve_minutes_medium > 0),
    first_response_minutes_low       INT          NOT NULL DEFAULT 1440  CHECK (first_response_minutes_low > 0),
    resolve_minutes_low              INT          NOT NULL DEFAULT 10080 CHECK (resolve_minutes_low > 0),
    ai_confidence_threshold          NUMERIC(3,2) NOT NULL DEFAULT 0.60  CHECK (ai_confidence_threshold BETWEEN 0 AND 1)
);

